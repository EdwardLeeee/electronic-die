#!/usr/bin/env python3
"""Quartus II 9.0 SP2 variant projects for the electronic die.

    python3 -I tools/quartus.py generate          write <variant>/<variant>.qpf/.qsf
    python3 -I tools/quartus.py list              print variant names (for run_quartus.sh)
    python3 -I tools/quartus.py collect           summaries -> docs/results.md + docs/results.json

Every variant targets the same device and settings as the course baseline
(Stratix II EP2S15F484C3, fastest speed grade, no timing constraints), so the
numbers are directly comparable.  Projects live in
electronic-die/synth/quartus/variants/<variant>/; only the .qpf/.qsf and the
*.summary files Quartus writes are kept in git.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
QDIR = ROOT / "electronic-die" / "synth" / "quartus"
VDIR = QDIR / "variants"
RTL = "../../../../rtl/verilog/"          # relative to a variant directory

DEVICE = "EP2S15F484C3"
BASE_FILES = ["ca_cell.v", "rng64.v", "modulo_by_6.v"]
FAST_FILES = BASE_FILES + ["mod6_popcount.v", "mod6_residue.v", "electronic_die_fast.v"]

# name: (top, files, parameters, description)
VARIANTS: dict[str, tuple[str, list[str], dict[str, int], str]] = {
    "baseline":   ("electronic_die", BASE_FILES + ["electronic_die.v"], {},
                   "original structural design (course submission), device pinned"),
    "percent_s0": ("electronic_die_fast", FAST_FILES, {"CORE": 0, "STAGES": 0},
                   "new top, original % operator, no pipeline (wrapper sanity check)"),
    "percent_s1": ("electronic_die_fast", FAST_FILES, {"CORE": 0, "STAGES": 1},
                   "original % operator plus one output register (naive registered)"),
}
for s in range(4):
    VARIANTS[f"popcount_s{s}"] = ("electronic_die_fast", FAST_FILES, {"CORE": 1, "STAGES": s},
                                  f"two popcount trees then mod 3, {s} pipeline stage(s)")
for s in range(4):
    VARIANTS[f"residue_s{s}"] = ("electronic_die_fast", FAST_FILES, {"CORE": 2, "STAGES": s},
                                 f"mod-3 adder tree over base-4 digits, {s} pipeline stage(s)")

QPF = """QUARTUS_VERSION = "9.0"
DATE = "00:00:00  January 01, 2026"

# Revisions

PROJECT_REVISION = "{name}"
"""

QSF = """# Generated by tools/quartus.py: {desc}
set_global_assignment -name FAMILY "Stratix II"
set_global_assignment -name DEVICE {device}
set_global_assignment -name DEVICE_FILTER_SPEED_GRADE FASTEST
set_global_assignment -name TOP_LEVEL_ENTITY {top}
set_global_assignment -name ORIGINAL_QUARTUS_VERSION "9.0 SP2"
set_global_assignment -name LAST_QUARTUS_VERSION "9.0 SP2"
set_global_assignment -name USE_GENERATED_PHYSICAL_CONSTRAINTS OFF -section_id eda_blast_fpga
{files}{params}set_instance_assignment -name PARTITION_HIERARCHY root_partition -to | -section_id Top
set_global_assignment -name PARTITION_NETLIST_TYPE SOURCE -section_id Top
set_global_assignment -name PARTITION_COLOR 16764057 -section_id Top
set_global_assignment -name LL_ROOT_REGION ON -section_id "Root Region"
set_global_assignment -name LL_MEMBER_STATE LOCKED -section_id "Root Region"
"""


def cmd_generate() -> int:
    for name, (top, files, params, desc) in VARIANTS.items():
        d = VDIR / name
        d.mkdir(parents=True, exist_ok=True)
        (d / f"{name}.qpf").write_text(QPF.format(name=name))
        f = "".join(f"set_global_assignment -name VERILOG_FILE {RTL}{x}\n" for x in files)
        p = "".join(f"set_parameter -name {k} {v}\n" for k, v in params.items())
        (d / f"{name}.qsf").write_text(QSF.format(desc=desc, device=DEVICE, top=top, files=f, params=p))
        for x in files:
            if not (d / (RTL + x)).resolve().exists():
                print(f"missing source {x} for {name}", file=sys.stderr)
                return 1
    print(f"wrote {len(VARIANTS)} variants under {VDIR.relative_to(ROOT)}")
    return 0


def cmd_list() -> int:
    print(" ".join(VARIANTS))
    return 0


def _fields(path: Path) -> dict[str, str]:
    out = {}
    for line in path.read_text(errors="replace").splitlines():
        if " : " in line:
            k, v = line.split(" : ", 1)
            out.setdefault(k.strip(), v.strip())
    return out


def _tan(path: Path) -> dict[str, dict[str, str]]:
    """Classic Timing Analyzer summary: blocks separated by blank lines, keyed by Type."""
    blocks, cur = {}, {}
    for line in path.read_text(errors="replace").splitlines():
        if " : " in line or line.rstrip().endswith(":"):
            k, _, v = line.partition(":")
            cur[k.strip()] = v.strip()
        elif not line.strip() and cur:
            if "Type" in cur:
                blocks[cur["Type"]] = cur
            cur = {}
    if cur.get("Type"):
        blocks[cur["Type"]] = cur
    return blocks


def _num(s: str) -> float | None:
    m = re.search(r"[-\d.,]+", s or "")
    return float(m.group(0).replace(",", "")) if m else None


def critical_path(d: Path, name: str) -> dict:
    """Keep the Classic Timing Analyzer's explanation of the internal fmax.

    The full .tan.rpt is not committed; this short excerpt is, as
    <variant>.critical_path.txt, so the delay numbers in docs/results.md can
    be checked against a file in the repository.
    """
    rpt, out = d / f"{name}.tan.rpt", d / f"{name}.critical_path.txt"
    if rpt.exists():
        lines = rpt.read_text(errors="replace").splitlines()
        for i, line in enumerate(lines):
            if line.startswith('Info: Clock "clk"') and "Internal fmax" in line:
                block = [line]
                for nxt in lines[i + 1:]:
                    if not nxt.startswith(" "):
                        break
                    block.append(nxt.rstrip())
                out.write_text("\n".join(block) + "\n")
                break
    if not out.exists():
        return {}
    text = out.read_text()
    get = lambda pat: (float(m.group(1)) if (m := re.search(pat, text)) else None)
    return {
        "reg_to_reg_ns": get(r"Longest register to register delay is ([\d.]+) ns"),
        "skew_ns": get(r"Smallest clock skew is (-?[\d.]+) ns"),
        "micro_tco_ns": get(r"Micro clock to output delay of source is ([\d.]+) ns"),
        "micro_tsu_ns": get(r"Micro setup delay of destination is ([\d.]+) ns"),
    }


def summarize(d: Path, name: str) -> dict:
    fit, tan, mp = (d / f"{name}.{x}.summary" for x in ("fit", "tan", "map"))
    if not (fit.exists() and tan.exists()):
        return {"variant": name, "status": "not compiled"}
    f, t = _fields(fit), _tan(tan)
    clk = t.get("Clock Setup: 'clk'", {})
    actual = clk.get("Actual Time", "")
    m = re.search(r"([\d.]+) MHz \( period = ([\d.]+) ns \)", actual)
    return {
        "variant": name,
        "status": f.get("Fitter Status", "?"),
        "quartus": f.get("Quartus II Version", "?"),
        "device": f.get("Device", "?"),
        "top": f.get("Top-level Entity Name", "?"),
        "aluts": _num(f.get("Combinational ALUTs", "").split("/")[0]),
        "registers": _num(f.get("Total registers", "")),
        "fmax_mhz": float(m.group(1)) if m else None,
        "period_ns": float(m.group(2)) if m else None,
        "fmax_note": "restricted" if "Restricted" in actual else "",
        "critical_from": clk.get("From", ""),
        "critical_to": clk.get("To", ""),
        "tsu_ns": _num(t.get("Worst-case tsu", {}).get("Actual Time", "")),
        "tco_ns": _num(t.get("Worst-case tco", {}).get("Actual Time", "")),
        "map_aluts": _num(_fields(mp).get("Combinational ALUTs", "")) if mp.exists() else None,
        "map_registers": _num(_fields(mp).get("Total registers", "")) if mp.exists() else None,
        **critical_path(d, name),
    }


def cmd_collect() -> int:
    rows = [dict(summarize(QDIR, "electronic_die"), variant="course (June 2026, Windows)")]
    rows += [dict(summarize(VDIR / n, n), description=VARIANTS[n][3], params=VARIANTS[n][2]) for n in VARIANTS]
    rows[0]["description"] = "as submitted for the course, Quartus on Windows"
    base = next((r for r in rows if r["variant"] == "baseline" and r.get("fmax_mhz")), None)
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "results.json").write_text(json.dumps(rows, indent=2) + "\n")

    lines = [
        "# Synthesis results",
        "",
        "Generated by `python3 -I tools/quartus.py collect` from the `*.summary` files that",
        "Quartus II 9.0 SP2 wrote in `electronic-die/synth/quartus/`. Do not edit by hand.",
        "",
        "All rows: Stratix II EP2S15F484C3 (fastest speed grade), default settings, no timing",
        "constraints, Classic Timing Analyzer. These are post-fit synthesis estimates; nothing",
        "was run on a board.",
        "",
        "| Variant | Mod-6 stage | Stages | ALUTs | Registers | fmax (MHz) | Speed-up | Reg-to-reg path (ns) | Critical path |",
        "|---|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for r in rows:
        if r.get("status") == "not compiled":
            lines.append(f"| {r['variant']} | {r.get('description', '')} | | | | not compiled | | | |")
            continue
        fm = r["fmax_mhz"]
        capped = bool(r["fmax_note"])
        sp = f"{fm / base['fmax_mhz']:.1f}x" if base and fm else ""
        st = r.get("params", {}).get("STAGES", 0)
        regs = f"{r['registers']:.0f}"
        if r.get("map_registers") is not None and r["map_registers"] != r["registers"]:
            regs += f" ({r['map_registers']:.0f}+{r['registers'] - r['map_registers']:.0f} dup.)"
        delay = ""
        if r.get("reg_to_reg_ns") is not None:
            delay = f"{r['reg_to_reg_ns'] + r['micro_tco_ns'] + r['micro_tsu_ns'] - r['skew_ns']:.3f}"
        path = f"`{r['critical_from']}` to `{r['critical_to']}`"
        lines.append(
            f"| {r['variant']} | {r.get('description', '')} | {st} | {r['aluts']:.0f} | {regs} | "
            f"{fm:.2f}{' (cap)' if capped else ''} | {sp}{' (cap)' if capped else ''} | {delay} | {path} |")
    lines += [
        "",
        "- **Speed-up** is relative to the `baseline` row (the course design recompiled with the",
        "  device pinned; its summaries are identical to the June course run in the first row).",
        "- **(cap)**: the Classic Timing Analyzer reports \"fmax restricted to clock pin edge rate 2.0 ns\":",
        "  500 MHz is the limit of the clock input pin, not of a logic path. The",
        "  register-to-register column shows how much of the 2.000 ns period the slowest path",
        "  actually needs.",
        "- **Reg-to-reg path** = longest register-to-register delay + micro tco + micro tsu - clock",
        "  skew, from `<variant>.critical_path.txt` (an excerpt of the timing report kept in git).",
        "- **dup.**: the fitter duplicated a register for routability (named `~DUPLICATE` in the",
        "  fitter report); the synthesis (map) count is shown first.",
        "- Pipelined variants answer `STAGES` clocks later; `en` keeps its meaning (it gates the",
        "  commit into `result_reg`). See docs/verification.md, section 4.",
        "",
    ]
    (ROOT / "docs" / "results.md").write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


def main(argv: list[str]) -> int:
    cmds = {"generate": cmd_generate, "list": cmd_list, "collect": cmd_collect}
    if len(argv) != 1 or argv[0] not in cmds:
        print(__doc__)
        return 2
    return cmds[argv[0]]()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
